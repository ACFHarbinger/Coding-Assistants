#!/usr/bin/env bash
# Make the Linux libraries the Tauri build probes available.
#
# A normal machine installs them with apt. This script does that when
# passwordless sudo works. Otherwise it downloads the same debs and unpacks
# them under ~/.local/share/coding-assistants/sysroot, then writes
# dev-env.sh for the just recipes to source. Runtime libraries that are
# already on the system stay there; dangling dev symlinks are pointed at
# those copies.

set -euo pipefail

ENV_FILE="${HOME}/.local/share/coding-assistants/dev-env.sh"
SYSROOT="${HOME}/.local/share/coding-assistants/sysroot"
CACHE="${HOME}/.cache/coding-assistants/debs"
APT_PACKAGES=(
    pkgconf
    libdbus-1-dev
    libwebkit2gtk-4.1-dev
    libjavascriptcoregtk-4.1-dev
    libgtk-3-dev
    libsoup-3.0-dev
    libayatana-appindicator3-dev
    librsvg2-dev
    libxdo-dev
    libssl-dev
    build-essential
    curl
    wget
    file
)
MODULES=(
    dbus-1
    webkit2gtk-4.1
    javascriptcoregtk-4.1
    gtk+-3.0
    libsoup-3.0
    librsvg-2.0
    ayatana-appindicator3-0.1
)

modules_ready() {
    local module
    for module in "${MODULES[@]}"; do
        pkg-config --exists "$module" || return 1
    done
}

write_neutral_env() {
    mkdir -p "$(dirname "$ENV_FILE")"
    cat >"$ENV_FILE" <<'EOF'
# The system pkg-config already sees the libraries this app builds against.
export CA_DEV_ENV_LOADED=1
EOF
}

write_sysroot_env() {
    mkdir -p "$(dirname "$ENV_FILE")"
    cat >"$ENV_FILE" <<EOF
# Generated by tools/dev/ensure-linux-dev-libs.sh
# Shell-only library prefix. Do not source this twice in one shell.
if [[ "\${CA_DEV_ENV_LOADED-}" != 1 ]]; then
    export CA_DEV_ENV_LOADED=1
    export PKG_CONFIG_ALLOW_SYSTEM_CFLAGS=1
    export PKG_CONFIG_ALLOW_SYSTEM_LIBS=1
    export PKG_CONFIG_PATH="${SYSROOT}/usr/lib/x86_64-linux-gnu/pkgconfig:${SYSROOT}/usr/lib/pkgconfig:${SYSROOT}/usr/share/pkgconfig\${PKG_CONFIG_PATH:+:\$PKG_CONFIG_PATH}"
    export LIBRARY_PATH="${SYSROOT}/usr/lib/x86_64-linux-gnu:${SYSROOT}/usr/lib\${LIBRARY_PATH:+:\$LIBRARY_PATH}"
    export LD_LIBRARY_PATH="${SYSROOT}/usr/lib/x86_64-linux-gnu:${SYSROOT}/usr/lib\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
fi
EOF
}

rewrite_pc_files() {
    local pc
    while IFS= read -r -d '' pc; do
        sed -i -E \
            -e "s|^(prefix=)/usr[[:space:]]*$|\\1${SYSROOT}/usr|" \
            -e "s|^(exec_prefix=)/usr[[:space:]]*$|\\1${SYSROOT}/usr|" \
            -e "s|^(libdir=)/usr/|\\1${SYSROOT}/usr/|" \
            -e "s|^(includedir=)/usr/|\\1${SYSROOT}/usr/|" \
            -e "s|-I/usr/|-I${SYSROOT}/usr/|g" \
            -e "s|-L/usr/|-L${SYSROOT}/usr/|g" \
            "$pc"
    done < <(find "$SYSROOT" -name '*.pc' -print0)
}

fix_library_symlinks() {
    local link target base dir
    [[ -d "$SYSROOT/usr/lib" ]] || return 0
    while IFS= read -r -d '' link; do
        [[ -e "$link" ]] && continue
        target="$(readlink "$link")"
        base="$(basename "$target")"
        for dir in /usr/lib/x86_64-linux-gnu /lib/x86_64-linux-gnu /usr/lib; do
            if [[ -e "$dir/$base" ]]; then
                ln -sfn "$dir/$base" "$link"
                break
            fi
        done
    done < <(find "$SYSROOT/usr/lib" -type l -print0)
}

install_with_sudo() {
    sudo -n apt-get update
    sudo -n apt-get install -y "${APT_PACKAGES[@]}"
}

install_into_sysroot() {
    local pkg deb
    mkdir -p "$CACHE" "$SYSROOT"
    mapfile -t packages < <(apt-get -s install "${APT_PACKAGES[@]}" | awk '/^Inst / { print $2 }' | sort -u)
    if [[ "${#packages[@]}" -eq 0 ]]; then
        echo "apt did not report any packages to install." >&2
        return 1
    fi
    echo "Downloading ${#packages[@]} packages into ${CACHE}"
    (
        cd "$CACHE"
        for pkg in "${packages[@]}"; do
            if compgen -G "${pkg}_*.deb" >/dev/null; then
                continue
            fi
            if ! apt-get download "$pkg"; then
                echo "warning: could not download ${pkg}" >&2
            fi
        done
    )
    shopt -s nullglob
    debs=("$CACHE"/*.deb)
    shopt -u nullglob
    if [[ "${#debs[@]}" -eq 0 ]]; then
        echo "No debs were downloaded." >&2
        return 1
    fi
    rm -rf "$SYSROOT"
    mkdir -p "$SYSROOT"
    for deb in "${debs[@]}"; do
        dpkg-deb -x "$deb" "$SYSROOT"
    done
    rewrite_pc_files
    fix_library_symlinks
    write_sysroot_env
}

# A previous run may already have written a sysroot env file. Source it
# before deciding the libraries are missing, or every `just start` wipes
# the sysroot and downloads the debs again.
if [[ -f "$ENV_FILE" ]]; then
    # shellcheck disable=SC1090
    source "$ENV_FILE" || true
    if modules_ready; then
        echo "Linux dev libraries already visible to pkg-config."
        exit 0
    fi
fi

if modules_ready; then
    write_neutral_env
    echo "Linux dev libraries already visible to pkg-config."
    exit 0
fi

if sudo -n true >/dev/null 2>&1; then
    echo "Installing Linux dev libraries with apt..."
    install_with_sudo
    if modules_ready; then
        write_neutral_env
        echo "Linux dev libraries installed."
        exit 0
    fi
fi

echo "sudo cannot prompt from this shell. Unpacking the dev libraries into ${SYSROOT}"
install_into_sysroot
# shellcheck disable=SC1090
source "$ENV_FILE"
if ! modules_ready; then
    echo "pkg-config still cannot see every required module:" >&2
    for module in "${MODULES[@]}"; do
        if ! pkg-config --exists "$module"; then
            echo "  missing ${module}" >&2
        fi
    done
    exit 1
fi
echo "Linux dev libraries ready under ${SYSROOT}"
pkg-config --modversion dbus-1 webkit2gtk-4.1 gtk+-3.0
